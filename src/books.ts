export const bookHasOneChapter = (bookName: string) => {
    for (const book of books) {
        if (
            (book.name.toLocaleLowerCase() === bookName.toLocaleLowerCase()) &&
            book.chapters === 1
        ) {
            return true   
        }
    }
    return false
}